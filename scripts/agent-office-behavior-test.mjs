import assert from 'node:assert/strict';
import {behaviorFor,createBehaviorTracker} from '../renderer/agent-office-behavior.js';
const a={id:'research',executionKey:'mac:task:research:1',status:'queued',commands:[]};
assert.equal(behaviorFor(a),'queued');assert.equal(behaviorFor({...a,status:'pending',waitingFor:['Plan']}),'dependency');
for(const [status,kind,expected] of [['working','reading','reading'],['running','writing','writing'],['working','tool','working'],['needs-you',null,'needs-input'],['completed',null,'completed'],['stopped','writing','stopped'],['blocked',null,'stopped']])assert.equal(behaviorFor({...a,status,activity:{kind}}),expected);
assert.equal(behaviorFor({...a,status:'working'},false),'offline');
const tracker=createBehaviorTracker(),active={...a,status:'working',activity:{kind:'writing'}};
assert.equal(tracker.update(active,true,100),'writing');
const queued={id:'instruction',operation:'update',status:'queued'},applied={...queued,status:'applied'};
assert.equal(tracker.update({...active,commands:[queued]},true,200),'writing');
assert.equal(tracker.update({...active,commands:[applied]},true,300),'acknowledge');
assert.equal(tracker.update({...active,status:'stopped',commands:[applied]},true,400),'stopped');
assert.equal(tracker.update({...active,status:'needs-you',commands:[applied]},true,450),'needs-input');
assert.equal(tracker.update({...active,commands:[applied]},true,1500),'writing');
assert.equal(tracker.update({...active,commands:[applied]},true,2000),'writing');
assert.equal(tracker.update({...active,executionKey:'phone:task:research:1',commands:[applied]},true,2100),'writing');
assert.equal(tracker.update({...active,status:'stopped',commands:[applied]},true,2200),'stopped');
assert.equal(tracker.update({...active,commands:[applied]},false,2300),'offline');
console.log('PASS all task-to-pose states, exact run/attempt identity, no queued acknowledgments, no history replays, interruption and offline precedence.');
